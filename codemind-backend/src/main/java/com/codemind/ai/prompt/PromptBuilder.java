package com.codemind.ai.prompt;

import org.springframework.stereotype.Component;

@Component
public class PromptBuilder {

    /**
     * 根据任务类型构建最终 Prompt
     *
     * @param taskType 任务类型
     * @param title    文章标题
     * @param content  文章内容
     * @return 最终 Prompt
     */
    public String build(AiTaskType taskType, String title, String content) {

        String taskPrompt = getTaskPrompt(taskType);

        return """
                # 角色
                你是一名专业的技术知识整理助手，负责帮助用户理解和学习技术文章。

                # 文章信息

                【文章标题】
                %s

                【文章内容】
                <<<ARTICLE_CONTENT>>>
                %s
                <<<END_ARTICLE_CONTENT>>>

                # 任务
                %s

                # 通用要求

                1. 你的回答必须以文章实际内容为依据，不得凭空编造文章中不存在的信息。
                2. 如果文章内容无法支持某个结论，请明确说明“文章中没有相关信息”。
                3. 保留 Java、Spring、Redis、MySQL 等技术名词，不要随意翻译。
                4. 对技术概念进行解释时，应尽量说明其原理，而不是只给出结论。
                5. 回答应该结构清晰，优先使用标题、列表等方式组织内容。
                6. 不要大段复制文章原文，应以总结、提炼和解释为主。
                7. 如果文章内容本身存在明显的不严谨之处，不要擅自修改为事实，可以指出“文章中的说法可能存在问题”。
                """.formatted(
                title,
                content,
                taskPrompt
        );
    }

    /**
     * 根据不同任务返回对应任务提示词
     */
    private String getTaskPrompt(AiTaskType taskType) {

        return switch (taskType) {

            case SUMMARY -> """
                    请对这篇技术文章进行总结。

                    要求：
                    1. 先用一句话概括文章主要解决的问题或核心主题。
                    2. 提炼文章中的主要内容和关键观点。
                    3. 对重要技术原理进行简洁解释。
                    4. 如果文章包含代码，只总结代码所体现的核心思路，不要大段复制代码。
                    5. 最后给出一份简洁的学习总结。

                    输出格式：

                    ## 一句话概括
                    ...

                    ## 核心内容
                    - ...
                    - ...
                    - ...

                    ## 关键技术
                    ### 1. xxx
                    说明：...

                    ### 2. xxx
                    说明：...

                    ## 总结
                    ...
                    """;

            case KNOWLEDGE_EXTRACT -> """
                    请从这篇技术文章中提取核心知识点，帮助用户建立技术知识体系。

                    要求：
                    1. 只提取文章中实际涉及的知识点，不要扩展文章没有涉及的内容。
                    2. 优先提取技术概念、原理、机制、设计思想和实践经验。
                    3. 对每个知识点进行简洁解释，说明“是什么”和“核心理解”。
                    4. 如果多个知识点存在关联，请体现它们之间的关系。
                    5. 最后列出最值得优先掌握的 3～5 个知识点。

                    输出格式：

                    ## 知识点分类

                    ### 一、基础概念
                    - **知识点：xxx**
                      - 是什么：...
                      - 核心理解：...

                    ### 二、核心原理
                    - **知识点：xxx**
                      - 是什么：...
                      - 核心理解：...

                    ### 三、实践与设计
                    - **知识点：xxx**
                      - 是什么：...
                      - 核心理解：...

                    ## 知识点之间的关系
                    ...

                    ## 优先掌握
                    1. xxx
                    2. xxx
                    3. xxx
                    """;

            case INTERVIEW -> """
                    请根据这篇技术文章生成 Java 后端面试题。

                    要求：
                    1. 面试题必须基于文章实际内容。
                    2. 不要为了凑题目而加入文章没有涉及的技术。
                    3. 按照基础、进阶、深入三个层次组织问题。
                    4. 每道题给出参考答案。
                    5. 参考答案应该解释原理，而不是只给一句结论。
                    6. 标注每道题主要考察的知识点。
                    7. 最后整理出最值得复习的高频问题。

                    输出格式：

                    ## 一、基础题

                    ### 1. 问题
                    **参考答案：**
                    ...

                    **考察点：**
                    ...

                    ## 二、进阶题

                    ### 1. 问题
                    **参考答案：**
                    ...

                    **考察点：**
                    ...

                    ## 三、深入题

                    ### 1. 问题
                    **参考答案：**
                    ...

                    **考察点：**
                    ...

                    ## 四、重点复习题
                    1. xxx
                    2. xxx
                    3. xxx
                    4. xxx
                    5. xxx
                    """;
        };
    }
}